  station text not null check (station in ('ΣΟΚ FM', 'DALKAS', 'ΜΠΛΕ', 'NRG')),
  slot text not null,
  listeners_k numeric(6, 2) not null check (listeners_k >= 0),
  sort integer not null,
  version integer not null default 1,
  updated_at timestamptz not null default now(),
  updated_by uuid references profiles (id),
  primary key (station, slot)
);
create trigger station_slots_version before update on station_slots for each row execute function trg_versioning();
